void main(List<String> args) {
  //declaracao por inferencia
  var nomeCurso = "Fundamentos Dart";
  print("Curso: ${nomeCurso}");

  //Modificador FINAL
  //Uma variavel declarada como final pode ser atribuida apenas uma vez e seu valor não pode ser alterado

  final nomeCursoFinal = "Fundamentos Dart";
  print("Curso final: ${nomeCursoFinal}");

  //Modificador CONST
  //Uma variavel declarada como CONST pode ser atribuida apenas uma vez e seu valor não pode ser alterado

}
